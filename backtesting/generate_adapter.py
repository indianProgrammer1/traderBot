"""Build an offline adapter from byte-identical, audited source fragments.

Existing source files are read only. Every generated artifact is placed in
backtesting/build. Source drift fails closed: review before updating the pins.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
BUILD = HERE / "build"
EXPECTED = {
    "traderBot/main.cpp": "2a175ea48702370024aa59dc0ef2a93a22d849bdf5cd60fcc674291288fad05d",
    "traderBot/DataFetcher.cpp": "c7dda4713aea0dc80dfec698fae9f79b39f15ac09d1b11671eec1863c86e7318",
    "traderBot/DataFetcher.h": "eaf9ec08cd1fa8cb9d12a6fe05e65f7d6b143e97209dd1e8db492d1cd7a36499",
    "traderBot/OrderInstructions.h": "89c7db068b78931ffc4e9d90a1879b91fee08e7243428d07a52f7d00f7811a11",
}


def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def generate() -> dict:
    selection_path = HERE / "source_selection.json"
    selection = json.loads(selection_path.read_text(encoding="utf-8")) if selection_path.is_file() else None
    source_paths = {relative: ROOT / relative for relative in EXPECTED}
    current_main_sha = sha((ROOT / "traderBot/main.cpp").read_bytes())
    if selection is not None:
        if (selection.get("mode") != "original_audited_snapshot" or
                selection.get("snapshot_path") != "source_snapshot/main.cpp" or
                selection.get("selected_main_sha256") != EXPECTED["traderBot/main.cpp"] or
                not selection.get("authorization")):
            raise RuntimeError("Invalid source selection; refusing to choose a different strategy")
        snapshot = (HERE / selection["snapshot_path"]).resolve()
        if not snapshot.is_relative_to((HERE / "source_snapshot").resolve()):
            raise RuntimeError("Selected snapshot must remain under backtesting/source_snapshot")
        if selection.get("observed_current_main_sha256") != current_main_sha:
            raise RuntimeError("Production main.cpp changed again after source selection; review required")
        source_paths["traderBot/main.cpp"] = snapshot
    sources = {}
    for relative, digest in EXPECTED.items():
        data = source_paths[relative].read_bytes()
        if sha(data) != digest:
            raise RuntimeError(f"Audited source changed: {relative}; refusing stale adapter")
        sources[relative] = data
    main = sources["traderBot/main.cpp"]
    fetcher = sources["traderBot/DataFetcher.cpp"]

    def lines(data: bytes, first: int, last: int, sentinel: bytes) -> bytes:
        fragment = b"".join(data.splitlines(keepends=True)[first - 1:last])
        if sentinel not in fragment or data.count(fragment) != 1:
            raise RuntimeError(f"Ambiguous audited fragment at lines {first}-{last}")
        return fragment

    fragments = {
        "analyzeData": ("traderBot/main.cpp", 289, 337,
                        lines(main, 289, 337, b"bool analyzeData(")),
        "quantity": ("traderBot/main.cpp", 172, 173,
                     lines(main, 172, 173, b"std::floor(std::abs(risk /")),
        "exit_condition": ("traderBot/main.cpp", 209, 210,
                           lines(main, 209, 210, b"positions[symbol].second")),
        "entry_time": ("traderBot/DataFetcher.cpp", 47, 48,
                       lines(fetcher, 47, 48, b"return timeOfDay >= hours{ 16 }")),
    }
    BUILD.mkdir(parents=True, exist_ok=True)
    prelude = b"""#pragma once
#ifndef NOMINMAX
#define NOMINMAX
#endif
#include <algorithm>
#include <cmath>
#include <cstdint>
#include <limits>
#include <string>
#include <vector>
"""
    (BUILD / "prelude.h").write_bytes(prelude)
    adapter = bytearray(b'''// Generated by generate_adapter.py. Original source fragments are verbatim.
#include "../strategy_adapter.h"
#include <chrono>
#include <unordered_map>
#include <utility>

const char* RED = "";
const char* GREEN = "";
const char* YELLOW = "";
const char* RESET = "";

''')
    adapter += fragments["analyzeData"][3]
    adapter += b'''
namespace bt {
bool validTime(std::int64_t epoch) {
    using namespace std::chrono;
    const zoned_time israelTime{locate_zone("Asia/Jerusalem"), sys_seconds{seconds{epoch}}};
    const auto localNow = israelTime.get_local_time();
    const auto today = floor<days>(localNow);
    const auto timeOfDay = localNow - today;
'''
    adapter += fragments["entry_time"][3]
    adapter += b'''}

bool signal(OrderInstructions& instructions, DataFetcher& fetcher,
            const std::vector<Bar>& daily, const std::vector<Bar>& five,
            const std::vector<Bar>& realtime, std::int64_t evaluation_epoch) {
    if (daily.size() < 15 || five.size() < 200 || realtime.empty()) return false;
    return analyzeData(instructions, fetcher.getContract().symbol,
        fetcher.getAtr(daily), fetcher.getSma10(five), fetcher.getSma20(five),
        fetcher.getSma200(five), fetcher.lastUpdatePrice(realtime),
        validTime(evaluation_epoch), fetcher.getYesterdayClose(daily),
        fetcher.validBar(five), fetcher.getVolume(), fetcher.todayOpenPrice(daily),
        fetcher.GapCheck(fetcher.getYesterdayClose(daily), fetcher.lastUpdatePrice(realtime)),
        fetcher.QQQtrendCheck(), fetcher.priceOptmization(fetcher.lastUpdatePrice(realtime)));
}

int quantity(DataFetcher& fetcher, const std::vector<Bar>& five,
             double lastPrice, const std::string& action) {
    if (five.size() < 2 || (action != "BUY" && action != "SELL")) return 0;
    double candleLow = fetcher.getCandleLow(five);
    double candleHigh = fetcher.getCandleHigh(five);
    double risk = fetcher.getRisk();
    // The live source converts a quotient to int before checking it. The replay
    // rejects undefined conversion inputs explicitly, without assigning a fill.
    const double distance = action == "BUY" ? lastPrice - candleLow : candleHigh - lastPrice;
    if (!std::isfinite(distance) || distance == 0 || lastPrice == candleLow) return 0;
    const double raw = std::floor(std::abs(risk / distance));
    if (!std::isfinite(raw) || raw < 0 || raw > (std::numeric_limits<int>::max)()) return 0;
    OrderInstructions instructions{};
    instructions.action = action;
    int quantity;
'''
    adapter += fragments["quantity"][3]
    adapter += b'''    return quantity;
}

bool exitSignal(const std::string& side, double price, double sma10) {
    const double lastPrice = price;
    const std::string symbol = "replay";
    std::unordered_map<std::string, std::pair<int, std::string>> positions{
        {symbol, {0, side}}
    };
'''
    adapter += fragments["exit_condition"][3]
    adapter += b'''        return true;
    }
    return false;
}
} // namespace bt
'''
    generated = bytes(adapter)
    for name, (_, _, _, fragment) in fragments.items():
        if generated.count(fragment) != 1:
            raise RuntimeError(f"Generated source does not preserve fragment: {name}")
    (BUILD / "strategy_adapter.generated.cpp").write_bytes(generated)
    manifest = {
        "source_sha256": EXPECTED,
        "source_paths": {relative: str(path.resolve()) for relative, path in source_paths.items()},
        "source_selection": selection,
        "observed_current_main_sha256": current_main_sha,
        "fragments": {
            name: {"source": source, "first_line": first, "last_line": last,
                   "sha256": sha(data), "bytes": len(data)}
            for name, (source, first, last, data) in fragments.items()
        },
        "generated_sha256": sha(generated),
        "break_even": "absent_in_inspected_source",
        "stop_loss_order": "absent_in_inspected_source",
    }
    (BUILD / "adapter_manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    return manifest


if __name__ == "__main__":
    result = generate()
    print(f"Verified {len(EXPECTED)} source hashes; generated {len(result['fragments'])} byte-identical fragments.")
    if result["source_selection"] is not None:
        print("Strategy source: user-selected original audited main.cpp snapshot with SMA10 exits; current production file remains unchanged.")
